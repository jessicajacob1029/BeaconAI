"""Render reports/explainability.md. Pure string building."""

from __future__ import annotations

from typing import Any

from beaconai.explain.explainer import ExplainedPrediction

DISCLAIMER = (
    "BeaconAI is decision support, not diagnosis. This model is trained only on synthetic "
    "data (DDXPlus) and is not a medical device."
)


def contrast_sentence(explained: ExplainedPrediction, true_condition: str | None = None) -> str:
    """One plain sentence: why the top condition rather than the runner-up."""
    con = explained.contrast
    if con is None:
        return ""

    def items(xs: list) -> str:
        return ", ".join(f"{x.description} ({x.contribution:+.2f})" for x in xs[:3]) or "nothing"

    kind = "abstains" if explained.prediction.kind == "abstain" else "answers"
    if con.ranking_changed_by_calibration:
        # The model's own scores favor the runner-up: say so first, never present it as support.
        text = (
            f"BeaconAI {kind}. {con.note} The model's own scores favor {con.versus}: "
            f"{items(con.favors_versus)}. Evidence for {con.condition}: "
            f"{items(con.favors_condition)}."
        )
    else:
        text = (
            f"BeaconAI {kind}. Why {con.condition} rather than {con.versus}: "
            f"{items(con.favors_condition)}. Pointing to {con.versus} instead: "
            f"{items(con.favors_versus)}."
        )
    if true_condition:
        text += f" (True condition: {true_condition}.)"
    return text


def render_explainability(summary: dict[str, Any], *, review_md: str | None) -> str:
    champ, base, lat = summary["champion"], summary["baseline"], summary["latency_ms"]
    rank = summary["ranking"]
    within = lat["p95"] <= lat["budget"]
    scope = "dev subsample" if summary["dev_sample"] else "full dataset"
    out = [
        "# Explainability",
        "",
        f"> {DISCLAIMER}",
        "",
        "Generated by `make explain`. Do not edit by hand. Decision record: "
        "`docs/phase4_explainability.md`.",
        "",
        f"Model: `beaconai-classifier` version {champ['version']}: {champ['model']} + "
        f"{champ['method']} (calibrated on {champ['calibrated_on']}). Data: DDXPlus {scope}.",
        "",
        "## How to read these explanations",
        "",
        "- They are exact for this linear model, in its logit space before isotonic calibration. "
        "Calibration changes the probabilities shown to the user, not these scores.",
        "- Each contribution is measured against a baseline patient with no evidence and the "
        f"training-average age and sex: average age {base['age_mean']:.1f}, "
        f"{base['male_share']:.0%} male (from the {base['source']}, "
        f"{base['n_patients']:,} patients). So a female and a male patient both get a sex "
        "contribution with the same meaning, and the baseline score plus all contributions "
        "equals the model's score exactly.",
        "- A single-condition explanation is relative to the average condition: the model's "
        "coefficients are only defined up to a constant shared by all conditions, and the "
        "fitted ones are centered (largest per-feature mean across conditions: "
        f"{summary['centering_max_abs_mean']:.4f}).",
        "- The most useful explanation is the contrast, why the top condition rather than the "
        "runner-up, which has no such ambiguity.",
        "",
        "## Does calibration change the ranking?",
        "",
        "Held-out validation patients: how often the order shown to the user (calibrated, with "
        "exact ties broken by the model's own score) differs from the model's own order.",
        "",
        "| Evidence | Top-1 changed | Top-3 set changed | Shown set changed "
        f"(conditions at {summary['ranking_min_prob']:.0%} or more) |",
        "|---|---:|---:|---:|",
        *[
            f"| {label} | {rank[key]['top1_changed']:.1%} | {rank[key]['topk_set_changed']:.1%} "
            f"| {rank[key]['shown_set_changed']:.2%} |"
            for label, key in (("Full evidence", "full"), ("Partial evidence", "partial"))
        ],
        "",
        "Isotonic calibration maps many small probabilities to the same value, so most changes "
        "in the top-3 set are among conditions the user would not be shown. When the top two "
        "are flipped, the contrast says so (`ranking_changed_by_calibration`).",
        "",
        "## Latency",
        "",
        f"End to end (encode, calibrated prediction, explanation) on {lat['n']} real validation "
        f"patients: median {lat['median']:.1f} ms, p95 {lat['p95']:.1f} ms, "
        + (
            f"within the {lat['budget']:.0f} ms budget."
            if within
            else f"over the {lat['budget']:.0f} ms budget."
        ),
        "",
        "## Worked examples (held-out patients, partial evidence)",
        "",
        *[f"- {e}" for e in summary["examples"]],
        "",
        "## Global view",
        "",
        "Top features per condition by coefficient (the logit contribution when present, "
        "relative to the average condition). Prevalence is from the training split. Hatched "
        "bars are flagged for review.",
        "",
    ]
    flagged = 0
    for cond, items in summary["global"].items():
        out += [
            f"### {cond}",
            "",
            f"![{cond}]({summary['images'][cond]})",
            "",
            "| Feature | Coefficient | With condition | Overall | Flags |",
            "|---|---:|---:|---:|---|",
        ]
        for t in items:
            flagged += bool(t["flags"])
            out.append(
                f"| {t['label']} | {t['coef']:.3f} | {t['prevalence_condition']:.1%} | "
                f"{t['prevalence_all']:.1%} | {', '.join(t['flags'])} |"
            )
        out.append("")
    out += [
        "## Sanity check",
        "",
        f"Automatic flags: {flagged} of the listed top features. A flag means: rarely seen with "
        "the condition (under the configured prevalence), less common with the condition than "
        "overall yet pushing toward it (usually collinearity), or a demographic feature. Flags "
        "are prompts for review, not errors.",
        "",
        review_md.strip() if review_md else "Human review pending.",
        "",
    ]
    return "\n".join(out)
