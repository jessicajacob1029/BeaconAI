"""Render reports/model_comparison.md from evaluation results. Pure string building."""

from __future__ import annotations

import json
import math
import re
from collections.abc import Sequence
from dataclasses import dataclass
from typing import Any

# Main table. Normalized differential recall@3 is the headline differential metric.
COLUMNS = [
    ("top1_accuracy", "Top-1"),
    ("top3_accuracy", "Top-3"),
    ("top5_accuracy", "Top-5"),
    ("macro_f1", "Macro F1"),
    ("ddx_recall_norm_at3", "DDx nR@3"),
]
DISCLAIMER = (
    "BeaconAI is decision support, not diagnosis. These models are trained only on "
    "synthetic data (DDXPlus) and are not a medical device."
)
_DDX_K = re.compile(r"^ddx_recall_norm_at(\d+)$")


@dataclass(frozen=True)
class ComparisonRow:
    model: str
    params: dict[str, Any]
    val: dict[str, float]
    test: dict[str, float] | None
    fit_seconds: float
    latency_ms: float


@dataclass(frozen=True)
class ConfusionPair:
    true_name: str
    pred_name: str
    count: int
    rate: float
    true_severity: int | None
    pred_severity: int | None


def _fmt(x: float | None) -> str:
    return "n/a" if x is None or math.isnan(x) else f"{x:.3f}"


def _values(row: ComparisonRow, split: str) -> dict[str, float]:
    return (row.val if split == "validate" else row.test) or {}


def _metric_table(rows: list[ComparisonRow], split: str) -> list[str]:
    present = [(k, t) for k, t in COLUMNS if any(k in _values(r, split) for r in rows)]
    lines = [
        "| Model | " + " | ".join(t for _, t in present) + " |",
        "|---|" + "---:|" * len(present),
    ]
    for r in rows:
        vals = _values(r, split)
        lines.append(f"| {r.model} | " + " | ".join(_fmt(vals.get(k)) for k, _ in present) + " |")
    return lines


def _ddx_table(rows: list[ComparisonRow], split: str) -> list[str]:
    lines = [
        "| Model | k | Precision@k | Recall@k (raw) | Recall@k (normalized) |",
        "|---|---:|---:|---:|---:|",
    ]
    for r in rows:
        vals = _values(r, split)
        ks = sorted(int(m.group(1)) for key in vals if (m := _DDX_K.match(key)))
        for k in ks:
            lines.append(
                f"| {r.model} | {k} | {_fmt(vals.get(f'ddx_precision_at{k}'))} | "
                f"{_fmt(vals.get(f'ddx_recall_at{k}'))} | "
                f"{_fmt(vals.get(f'ddx_recall_norm_at{k}'))} |"
            )
    return lines


def render_comparison(
    rows: list[ComparisonRow],
    *,
    split: str,
    champion: str,
    selection_metric: str,
    tie_breakers: Sequence[str] = (),
    dataset_note: str,
    confusions: list[ConfusionPair],
    lowest_recall: list[tuple[str, float]],
    confusion_image: str,
    recall_image: str,
) -> str:
    out = [
        "# Model comparison",
        "",
        f"> {DISCLAIMER}",
        "",
        "Generated by `make eval` (or `make eval-val`). Do not edit by hand; "
        "analysis lives in `docs/phase2_analysis.md`.",
        "",
        f"Data: {dataset_note}.",
        f"Selection: best validation `{selection_metric}`. Selected model: **{champion}**.",
        *(
            ["Exact ties are broken by " + ", then ".join(f"`{m}`" for m in tie_breakers) + "."]
            if tie_breakers
            else []
        ),
        "",
        "## Validation",
        "",
        *_metric_table(rows, "validate"),
        "",
        "## Test",
        "",
    ]
    if split == "test":
        out += [*_metric_table(rows, "test"), ""]
    else:
        out += ["Test split not evaluated yet. It is scored once, on the full dataset.", ""]
    out += [
        f"## Differential overlap ({split})",
        "",
        "Overlap between our top-k and the DDXPlus reference differential D "
        "(conditions with non-zero probability). Precision@k = hits / k. "
        "Raw recall@k = hits / |D|, which stays below 1 whenever D has more than k "
        "conditions. Normalized recall@k = hits / min(k, |D|), so 1.0 means our k slots "
        "hold as many reference conditions as possible. Normalized recall@3 is the "
        "headline differential metric (DDx nR@3 above).",
        "",
        *_ddx_table(rows, split),
        "",
        "## Cost",
        "",
        "| Model | Fit time (s) | Latency per patient (ms) | Params |",
        "|---|---:|---:|---|",
        *[
            f"| {r.model} | {r.fit_seconds:.1f} | {r.latency_ms:.2f} | `{json.dumps(r.params)}` |"
            for r in rows
        ],
        "",
        f"## Confusion matrix ({champion}, {split})",
        "",
        f"![Confusion matrix]({confusion_image})",
        "",
        "Rows are normalised: each row shows where patients with that true condition "
        "were predicted.",
        "",
        "### Most frequent confusions",
        "",
        "| True | Predicted as | Count | Share of true | Severity (true / predicted) |",
        "|---|---|---:|---:|---|",
        *[
            f"| {c.true_name} | {c.pred_name} | {c.count} | {_fmt(c.rate)} | "
            f"{c.true_severity} / {c.pred_severity} |"
            for c in confusions
        ],
        "",
        "Severity is from DDXPlus `release_conditions.json` (1 is most severe).",
        "",
        "### Lowest per-class recall",
        "",
        f"![Per-class recall]({recall_image})",
        "",
        "| Condition | Recall |",
        "|---|---:|",
        *[f"| {name} | {_fmt(r)} |" for name, r in lowest_recall],
        "",
    ]
    return "\n".join(out)
