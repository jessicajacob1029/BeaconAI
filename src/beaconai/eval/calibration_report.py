"""Render reports/calibration.md from the calibration summary. Pure string building."""

from __future__ import annotations

from typing import Any

DISCLAIMER = (
    "BeaconAI is decision support, not diagnosis. These models are trained only on "
    "synthetic data (DDXPlus) and are not a medical device."
)


def _f(x: float | None, digits: int = 3) -> str:
    return "n/a" if x is None else f"{x:.{digits}f}"


def eligibility(metrics: dict[str, float], floor: dict[str, float]) -> str:
    if metrics["top3_accuracy"] < floor["full"]:
        return "no, below the full top-3 floor"
    if metrics["partial_top3_accuracy"] < floor["partial"]:
        return "no, below the partial top-3 floor"
    return "yes"


def _evidence_table(candidates: list[dict[str, Any]], prefix: str, extra: str) -> list[str]:
    header = "| Model | Method | ECE | NLL | Top-1 | Top-3 | " + extra + " | Calibrated on |"
    rows = [header, "|---|---|---:|---:|---:|---:|---|---|"]
    for c in candidates:
        m = c["metrics"]
        rows.append(
            f"| {c['model']} | {c['method']} | {_f(m[prefix + 'ece'], 4)} | "
            f"{_f(m[prefix + 'nll'])} | {_f(m[prefix + 'top1_accuracy'])} | "
            f"{_f(m[prefix + 'top3_accuracy'])} | {c['_extra']} | {c.get('fit_on', 'full')} |"
        )
    return rows


def _same(c: dict[str, Any], ref: dict[str, Any]) -> bool:
    key = ("model", "method")
    return all(c[k] == ref[k] for k in key) and c.get("fit_on", "full") == ref.get("fit_on", "full")


def _comparison(summary: dict[str, Any], baseline: dict[str, Any]) -> list[str]:
    def row(label: str, c: dict[str, Any]) -> str:
        m = c["metrics"]
        return (
            f"| {label} | {c['model']} | {c['method']} | {c.get('fit_on', 'full')} | "
            f"{_f(m['partial_ece'], 4)} | {_f(m['partial_top3_accuracy'])} | "
            f"{_f(m['ece'], 4)} | {_f(m['top3_accuracy'])} |"
        )

    header = [
        "| | Model | Method | Calibrated on | ECE partial | Top-3 partial | ECE full "
        "| Top-3 full |",
        "|---|---|---|---|---:|---:|---:|---:|",
    ]
    old = next(c for c in baseline["candidates"] if _same(c, baseline["champion"]))
    new = next(c for c in summary["candidates"] if _same(c, summary["champion"]))
    return [
        "## Comparison with the Phase 3 baseline",
        "",
        "Same held-out rows and the same partial-evidence rule as Phase 3.",
        "",
        *header,
        row("Phase 3 champion", old),
        row("Phase 3b champion", new),
        "",
        "Phase 3 baseline, all candidates:",
        "",
        *header,
        *[row("Phase 3", c) for c in baseline["candidates"]],
        "",
    ]


def _curve_section(curve: dict[str, Any], image: str | None) -> list[str]:
    new, old = curve["champion"], curve.get("phase3_champion")
    lines = [
        "## Accuracy and calibration by number of known evidences",
        "",
        "Held-out patients keep the initial evidence plus n other random evidences (same rule "
        "as the partial-evidence evaluation).",
        "",
    ]
    if old is None:
        lines += ["| Other evidences | Top-3 | ECE |", "|---:|---:|---:|"]
        lines += [
            f"| {n} | {_f(t)} | {_f(e, 4)} |"
            for n, t, e in zip(curve["extra"], new["top3_accuracy"], new["ece"], strict=True)
        ]
    else:
        lines += [
            "| Other evidences | Top-3 (Phase 3) | Top-3 (Phase 3b) | ECE (Phase 3) "
            "| ECE (Phase 3b) |",
            "|---:|---:|---:|---:|---:|",
        ]
        lines += [
            f"| {n} | {_f(ot)} | {_f(nt)} | {_f(oe, 4)} | {_f(ne, 4)} |"
            for n, ot, nt, oe, ne in zip(
                curve["extra"],
                old["top3_accuracy"],
                new["top3_accuracy"],
                old["ece"],
                new["ece"],
                strict=True,
            )
        ]
    if image:
        lines += ["", f"![Known evidences]({image})"]
    return [*lines, ""]


def render_calibration(
    summary: dict[str, Any],
    *,
    ece_bins: int,
    reliability_images: dict[str, str],
    coverage_image: str,
    baseline: dict[str, Any] | None = None,
    curve_image: str | None = None,
) -> str:
    champ = summary["champion"]
    floor = summary["top3_floor"]
    abst = summary["abstention"]
    candidates = summary["candidates"]
    scope = "dev subsample" if summary["dev_sample"] else "full dataset"
    champ_m = next(c for c in candidates if _same(c, champ))["metrics"]

    out = [
        "# Calibration and abstention",
        "",
        f"> {DISCLAIMER}",
        "",
        "Generated by `make calibrate`. Do not edit by hand; the decision record is "
        "`docs/phase3_calibration.md`.",
        "",
        f"Data: DDXPlus {scope}, validation split. Calibrators are fit on {summary['n_fit']:,} "
        f"patients and every number below comes from the other {summary['n_held']:,}. "
        "The test split is not used.",
        f"ECE: top-label, {ece_bins} equal-width bins. Lower is better.",
        "",
        "Caveat: the held-out half is not fully independent of the models. Validation was "
        "already used in Phase 2 to tune hyperparameters and for early stopping, and the "
        "champion and threshold below are chosen on these same rows. Treat the numbers as "
        "somewhat optimistic until they are confirmed on the test split in the final evaluation.",
        "",
        f"Champion: **{champ['model']} + {champ['method']}** (calibrated on "
        f"{champ.get('fit_on', 'full')} rows), the lowest partial-evidence ECE "
        "among (model, method) pairs whose held-out top-3 accuracy is at least "
        f"{floor['full']:.3f} on full evidence and at least {floor['partial']:.3f} on partial "
        f"evidence. Registered as `{summary['registered']['name']}` version "
        f"{summary['registered']['version']}, alias `{summary['registered']['alias']}`.",
        "",
        "## Partial evidence (selection basis, held-out validation)",
        "",
        "Each patient keeps the initial evidence plus 3 other random evidences; age and sex are "
        "kept. This is closer to what a user tells us at the start of a conversation.",
        "",
        *_evidence_table(
            [{**c, "_extra": eligibility(c["metrics"], floor)} for c in candidates],
            "partial_",
            "Eligible",
        ),
        "",
        "## Full evidence (comparison, held-out validation)",
        "",
        *_evidence_table(
            [{**c, "_extra": _f(c["temperature"], 2)} for c in candidates], "", "Temperature"
        ),
        "",
        "## Limitation: not asked is read as no",
        "",
        "The models were trained on complete answers, where a missing evidence means the patient "
        "does not have it. With partial evidence, every question not asked yet is read the same "
        'way, as a "no". The table shows what that costs.',
        "",
        "| Model | Method | Top-3 full | Top-3 partial | Drop (points) | ECE full | ECE partial "
        "| Increase |",
        "|---|---|---:|---:|---:|---:|---:|---:|",
    ]
    for c in candidates:
        m = c["metrics"]
        drop = 100 * (m["top3_accuracy"] - m["partial_top3_accuracy"])
        rise = m["partial_ece"] - m["ece"]
        out.append(
            f"| {c['model']} | {c['method']} | {_f(m['top3_accuracy'])} | "
            f"{_f(m['partial_top3_accuracy'])} | {drop:.1f} | {_f(m['ece'], 4)} | "
            f"{_f(m['partial_ece'], 4)} | {rise:+.4f} |"
        )
    champ_drop = 100 * (champ_m["top3_accuracy"] - champ_m["partial_top3_accuracy"])
    out += [
        "",
        f"For the champion, top-3 accuracy drops from {_f(champ_m['top3_accuracy'])} to "
        f"{_f(champ_m['partial_top3_accuracy'])} ({champ_drop:.1f} points) and ECE rises from "
        f"{_f(champ_m['ece'], 4)} to {_f(champ_m['partial_ece'], 4)} when only the initial "
        "evidence and 3 others are known. Fixing this needs retraining (random evidence dropout, "
        "or a yes/no/not-asked encoding) before the Phase 8 question selector.",
        "",
        *(
            _comparison(summary, baseline)
            if baseline is not None and baseline.get("dev_sample") == summary["dev_sample"]
            else []
        ),
        *(
            _curve_section(summary["evidence_curve"], curve_image)
            if summary.get("evidence_curve")
            else []
        ),
        "## Reliability diagrams",
        "",
        *[f"![{name} reliability]({img})" for name, img in reliability_images.items()],
        "",
        "## Abstention",
        "",
        f"Threshold: {abst['threshold']:.2f}. BeaconAI abstains when the calibrated probability "
        "of the most likely condition is below this; equal is answered.",
        "",
    ]
    n_extra = abst.get("suggest_on_extra")
    who = (
        "answered partial-evidence patients"
        if n_extra is None
        else f"answered patients who know only the initial evidence plus {n_extra} other evidences"
    )
    if abst["suggested_threshold"] is None:
        out.append(
            f"No threshold reaches top-{abst['k']} accuracy of {abst['target_accuracy']:.2f} "
            f"for {who}."
        )
    else:
        out.append(
            f"Suggested threshold: {abst['suggested_threshold']:.2f} (smallest threshold whose "
            f"{who} reach top-{abst['k']} accuracy of {abst['target_accuracy']:.2f})."
        )
    rows = [("Full evidence", abst["full"]), ("Partial evidence", abst["partial"])]
    if n_extra is not None and abst.get("suggest_set"):
        rows.append((f"Initial evidence + {n_extra}", abst["suggest_set"]))
    out += [
        "",
        f"| Evidence | Answered | Top-1 on answered | Top-{abst['k']} on answered |",
        "|---|---:|---:|---:|",
        *[
            f"| {label} | {a['coverage']:.1%} | {_f(a['top1_accuracy'])} | "
            f"{_f(a['topk_accuracy'])} |"
            for label, a in rows
        ],
        "",
        f"![Coverage vs accuracy]({coverage_image})",
        "",
    ]
    return "\n".join(out)
